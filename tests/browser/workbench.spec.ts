test('seeded comparisons reproduce charts and stop/restart without stale updates', async ({ page }) => {
  await page.getByLabel('Workloads', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Run seeded comparison' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'workloads compared' })).toHaveText('3 / 3 workloads compared · complete.')
  const charts = await page.locator('.study-charts').innerText()
  await page.getByRole('button', { name: 'Run seeded comparison' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'workloads compared' })).toHaveText('3 / 3 workloads compared · complete.')
  await expect(page.locator('.study-charts')).toHaveText(charts, { useInnerText: true })
  // A larger batch leaves time for a real user to stop between workload rounds.
  await page.getByLabel('Workloads', { exact: true }).fill('100')
  await page.getByLabel('Processes per workload', { exact: true }).fill('12')
  await page.getByRole('button', { name: 'Run seeded comparison' }).click()
  await page.getByRole('button', { name: 'Stop comparison' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'workloads compared' })).toContainText('stopped; partial sample')
  await page.getByLabel('Random seed', { exact: true }).fill('17')
  await page.getByLabel('Workloads', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Run seeded comparison' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'workloads compared' })).toHaveText('1 / 1 workloads compared · complete.')
  await expect(page.getByText(/Results for: Seed 17/)).toBeVisible()
})

test('saving and share links restore a validated scenario at event zero', async ({ page }) => {
  await page.getByRole('button', { name: 'Save in browser' }).click()
  await expect(page.getByRole('status')).toContainText('Workload saved')
  await page.getByRole('button', { name: 'Create share link' }).click()
  const link = await page.getByLabel('Scenario share link', { exact: true }).inputValue()
  expect(new URL(link).pathname).toBe('/OS-Project/')
  await page.getByLabel('Preset').selectOption('preemption')
  await page.getByRole('button', { name: 'Load saved workload' }).click()
  await expect(page.getByRole('heading', { name: 'CPU + disk overlap', exact: true })).toBeVisible()
  await page.getByLabel('Preset').selectOption('preemption')
  await page.goto(link)
  await expect(page.getByRole('heading', { name: 'CPU + disk overlap', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('CPU Gantt chart')).toContainText('Advance the experiment')
  await page.goto('./#scenario=%XX')
  await expect(page.getByRole('alert')).toContainText('Invalid shared scenario')
  await expect(page.getByRole('heading', { name: 'CPU + disk overlap', exact: true })).toBeVisible()
})
