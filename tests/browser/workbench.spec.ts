import { expect, test, type Page } from '@playwright/test'

const runtimeErrors = new WeakMap<Page, string[]>()

test.beforeEach(async ({ page }) => {
  const errors: string[] = []
  runtimeErrors.set(page, errors)
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('response', (response) => {
    if (response.status() >= 400 && /\.(js|css)(\?|$)/.test(response.url())) errors.push(`Asset ${response.status()}: ${response.url()}`)
  })
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Inside the system.' })).toBeVisible()
})

test.afterEach(async ({ page }) => { expect(runtimeErrors.get(page)).toEqual([]) })

test('all four modes load, perform an operation and preserve the integrated run', async ({ page }) => {
  await page.getByRole('button', { name: 'Run to end', exact: true }).click()
  await expect(page.getByLabel('CPU Gantt chart')).toContainText('13–14')
  await page.getByRole('button', { name: 'Memory & algorithms', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A place for every byte.' })).toBeVisible()
  await page.getByRole('button', { name: 'Translation example: 5572' }).click()
  await expect(page.getByText(/physical byte address 5572/i)).toBeVisible()
  await page.getByRole('button', { name: 'Run references', exact: true }).click()
  await expect(page.getByText(/Hits 1 · Faults 7/)).toBeVisible()
  await page.getByRole('button', { name: 'Concurrency', exact: true }).click()
  await expect(page.getByRole('heading', { name: /One shared value/ })).toBeVisible()
  await page.getByRole('button', { name: 'Run lesson', exact: true }).click()
  await expect(page.locator('.integrated-stats').filter({ visible: true })).toContainText('Shared value1')
  await page.getByRole('button', { name: 'Resource safety', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Can everyone finish?' })).toBeVisible()
  await page.getByRole('button', { name: 'Evaluate request', exact: true }).click()
  await expect(page.getByText('DEFERRED', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Integrated system', exact: true }).click()
  await expect(page.getByLabel('CPU Gantt chart')).toContainText('13–14')
})

test('replay rewinds, restores the final timeline and resumes the same future', async ({ page }) => {
  await page.getByRole('button', { name: 'Run to end', exact: true }).click()
  const final = await page.getByLabel('CPU Gantt chart').innerText()
  await page.getByRole('button', { name: 'Prepare replay slider' }).click()
  await page.getByRole('slider', { name: 'Replay event' }).press('Home')
  await expect(page.getByLabel('CPU Gantt chart')).toContainText('Advance the experiment')
  await page.getByRole('slider', { name: 'Replay event' }).press('End')
  await expect(page.getByLabel('CPU Gantt chart')).toHaveText(final, { useInnerText: true })
  await page.getByRole('button', { name: '← Previous event' }).click()
  await page.getByRole('button', { name: '← Previous event' }).click()
  await page.getByRole('button', { name: 'Run to end', exact: true }).click()
  await expect(page.getByLabel('CPU Gantt chart')).toHaveText(final, { useInnerText: true })
})

